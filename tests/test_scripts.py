sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'net', 'gwswitch', 'src', 'opnsense', 'scripts', 'gwswitch'))

import lib  # noqa: E402
from watcher import Watcher  # noqa: E402

CONFIG = """# DO NOT EDIT THIS FILE -- OPNsense auto-generated file
[general]
enabled=1
interval=7
kill_states=1

[clients]
AA:BB:CC:DD:EE:01=gwsw_vpn1
aa:bb:cc:dd:ee:02=gwsw_vpn6
not-a-mac=gwsw_vpn1
aa:bb:cc:dd:ee:03=evil;rm -rf
"""

HOSTS = json.dumps({'source': 'arp-ndp', 'rows': [
    ['vtnet1', 'aa:bb:cc:dd:ee:01', '192.168.1.10'],
    ['vtnet1', 'aa:bb:cc:dd:ee:01', '2001:db8::10'],
    ['vtnet1', 'AA:BB:CC:DD:EE:01', 'fe80::1%vtnet1'],
    ['vtnet1', 'aa:bb:cc:dd:ee:02', '192.168.1.20'],
    ['vtnet1', '(incomplete)', '192.168.1.30'],
]})


class ConfigTest(unittest.TestCase):
    def setUp(self):
        handle, self.filename = tempfile.mkstemp()
        with os.fdopen(handle, 'w') as out:
            out.write(CONFIG)

    def tearDown(self):
        os.unlink(self.filename)

    def test_read_config(self):
        config = lib.read_config(self.filename)
        self.assertTrue(config['enabled'])
        self.assertEqual(config['interval'], 7)
        self.assertEqual(config['clients'], {'aa:bb:cc:dd:ee:01': 'gwsw_vpn1', 'aa:bb:cc:dd:ee:02': 'gwsw_vpn6'})

    def test_missing_config(self):
        self.assertEqual(lib.read_config('/nonexistent')['clients'], {})


class ParseTest(unittest.TestCase):
    def test_parse_hosts(self):
        hosts = lib.parse_hosts(HOSTS)
        self.assertEqual(set(hosts), {'aa:bb:cc:dd:ee:01', 'aa:bb:cc:dd:ee:02'})
        self.assertEqual(hosts['aa:bb:cc:dd:ee:01']['ipv4'], {'192.168.1.10'})
        self.assertEqual(hosts['aa:bb:cc:dd:ee:01']['ipv6'], {'2001:db8::10'})

    def test_parse_hosts_garbage(self):
        self.assertEqual(lib.parse_hosts('not json'), {})

    def test_parse_leases(self):
        payload = json.dumps({'records': [
            {'hwaddr': 'AA:BB:CC:DD:EE:01', 'hostname': 'laptop.'},
            {'hwaddr': 'aa:bb:cc:dd:ee:02', 'hostname': ''},
        ]})
        self.assertEqual(lib.parse_leases(payload), {'aa:bb:cc:dd:ee:01': 'laptop'})
        self.assertEqual(lib.parse_leases(''), {})

    def test_parse_killed(self):
        self.assertEqual(lib.parse_killed('killed 3 states from 1 sources and 0 destinations\n'), 3)
        self.assertEqual(lib.parse_killed(''), 0)


class WatcherTest(unittest.TestCase):
    def setUp(self):
        handle, self.filename = tempfile.mkstemp()
        with os.fdopen(handle, 'w') as out:
            out.write(CONFIG)
        self.tables = {'gwsw_vpn1': {'192.168.1.10'}, 'gwsw_vpn6': set()}
        self.killed = []

    def tearDown(self):
        os.unlink(self.filename)

    def tick(self, watcher):
        return watcher.tick(
            hosts=lib.parse_hosts(HOSTS),
            table_reader=lambda name: set(self.tables[name]),
            table_adder=lambda name, addresses: self.tables[name].update(addresses),
            state_killer=lambda address: self.killed.append(address) or 1,
        )

    def test_adds_new_addresses_and_kills_their_states(self):
        watcher = Watcher(self.filename)
        added = self.tick(watcher)
        self.assertEqual(added, {'gwsw_vpn1': ['2001:db8::10'], 'gwsw_vpn6': ['192.168.1.20']})
        self.assertEqual(sorted(self.killed), ['192.168.1.20', '2001:db8::10'])
        self.assertEqual(self.tables['gwsw_vpn1'], {'192.168.1.10', '2001:db8::10'})

    def test_second_tick_is_quiet(self):
        watcher = Watcher(self.filename)
        self.tick(watcher)
        self.killed = []
        self.assertEqual(self.tick(watcher), {})
        self.assertEqual(self.killed, [])


