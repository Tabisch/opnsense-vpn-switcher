class Helpers:
    """ minimal stand-in for the OPNsense template helpers """
    def __init__(self, data):
        self.data = data

    def _get(self, tag):
        node = self.data
        for part in tag.split('.'):
            if not isinstance(node, dict) or part not in node:
                return None
            node = node[part]
        return node

    def exists(self, tag):
        return self._get(tag) is not None

    def getNodeByTag(self, tag):
        return self._get(tag)

    def toList(self, tag):
        node = self._get(tag)
        return node if isinstance(node, list) else ([] if node is None else [node])

    def getUUID(self, uuid):
        for profile in self.toList('OPNsense.gwswitch.profiles.profile'):
            if profile.get('@uuid') == uuid:
                return profile
        return {}


@unittest.skipIf(jinja2 is None, 'jinja2 not installed')
class TemplateTest(unittest.TestCase):
    def render(self, name, data):
        env = jinja2.Environment(loader=jinja2.FileSystemLoader(TEMPLATES), extensions=['jinja2.ext.do'])
        return env.get_template(name).render(helpers=Helpers(data), **data)

    def data(self, enabled='1'):
        return {'OPNsense': {'gwswitch': {
            'general': {'enabled': enabled, 'interval': '5', 'kill_states': '1'},
            'profiles': {'profile': [
                {'@uuid': 'p1', 'enabled': '1', 'name': 'VPN1'},
                {'@uuid': 'p2', 'enabled': '0', 'name': 'off'},
            ]},
            'clients': {'client': [
                {'enabled': '1', 'mac': 'AA:BB:CC:DD:EE:01', 'profile': 'p1'},
                {'enabled': '1', 'mac': 'aa:bb:cc:dd:ee:02', 'profile': 'p2'},
                {'enabled': '1', 'mac': 'aa:bb:cc:dd:ee:03', 'profile': ''},
                {'enabled': '0', 'mac': 'aa:bb:cc:dd:ee:04', 'profile': 'p1'},
            ]},
        }}}

    def test_config(self):
        handle, filename = tempfile.mkstemp()
        with os.fdopen(handle, 'w') as out:
            out.write(self.render('gwswitch.conf', self.data()))
        try:
            config = lib.read_config(filename)
        finally:
            os.unlink(filename)
        self.assertEqual(config['clients'], {'aa:bb:cc:dd:ee:01': 'gwsw_vpn1'})
        self.assertEqual(config['interval'], 5)

    def test_rc_conf(self):
        self.assertIn('gwswitch_enable="YES"', self.render('rc.conf.d', self.data()))
        self.assertIn('gwswitch_enable="NO"', self.render('rc.conf.d', self.data('0')))
